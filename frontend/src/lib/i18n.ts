export function applyHtmlDirection(lang: string) {
  const isArabic = lang.startsWith('ar');
  const dir = isArabic ? 'rtl' : 'ltr';
  const langAttr = isArabic ? 'ar' : 'en';

  document.documentElement.dir = dir;
  document.documentElement.lang = langAttr;

  if (isArabic) {
    document.documentElement.classList.add('rtl');
    document.documentElement.classList.remove('ltr');
  } else {
    document.documentElement.classList.add('ltr');
    document.documentElement.classList.remove('rtl');
  }
}

// Initial sync based on saved preference or fallback
const initialLang =
  (typeof window !== 'undefined' &&
    (localStorage.getItem('inspect_language') ||
      localStorage.getItem('i18nextLng'))) ||
  'en';

const normalizedInitialLang = initialLang.startsWith('ar') ? 'ar' : 'en';

if (typeof window !== 'undefined') {
  applyHtmlDirection(normalizedInitialLang);
}

void i18n
  .use(LanguageDetector)
  .use(initReactI18next)
  .init({
    resources,
    fallbackLng: 'en',
    lng: normalizedInitialLang,
    detection: {
      order: ['localStorage', 'navigator'],
      lookupLocalStorage: 'inspect_language',
      caches: ['localStorage'],
    },
    interpolation: {
      escapeValue: false,
    },
  });

i18n.on('languageChanged', (lng) => {
  applyHtmlDirection(lng);
  try {
    localStorage.setItem('inspect_language', lng);
  } catch {
    // ignore
  }
});

export function changeAppLanguage(lang: SupportedLanguage) {
  applyHtmlDirection(lang);
  try {
    localStorage.setItem('inspect_language', lang);
  } catch {
    // ignore
  }
  return i18n.changeLanguage(lang);
}

export default i18n;
